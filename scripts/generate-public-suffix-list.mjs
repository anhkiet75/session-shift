import { writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const PSL_URL = 'https://publicsuffix.org/list/public_suffix_list.dat'

function escapeTemplateLiteral(value) {
  return value.replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${')
}

async function main() {
  const response = await fetch(PSL_URL)
  if (!response.ok) {
    throw new Error(`Failed to fetch PSL: ${response.status} ${response.statusText}`)
  }

  const source = await response.text()
  const lines = []

  for (const rawLine of source.split('\n')) {
    const line = rawLine.trim()
    if (!line) continue
    if (line.startsWith('//')) continue
    lines.push(line)
  }

  const output = `// Generated by scripts/generate-public-suffix-list.mjs
// Source: ${PSL_URL}
// Scope: ICANN and private sections

export const PSL_RULES = \`${escapeTemplateLiteral(lines.join('\n'))}\`
`

  const currentFile = fileURLToPath(import.meta.url)
  const projectRoot = path.resolve(path.dirname(currentFile), '..')
  const outputPath = path.join(projectRoot, 'src/lib/public-suffix-data.ts')

  await writeFile(outputPath, output, 'utf8')
  console.log(`Wrote ${lines.length} PSL rules to ${outputPath}`)
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error)
  process.exitCode = 1
})
